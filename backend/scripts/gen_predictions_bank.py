#!/usr/bin/env python3
"""Generate internal/database/ielts_predictions_bot_bank.go from the IELTS
predictions bot's cleaned topic JSON (~/ielts-predictions-bot/data).

Imports the bot's Writing Task 2 essays and Speaking Part 1/2/3 questions into
the StudyWithRaissov IELTS question bank (mockType=predictions). Speaking is
text-only (no audio), matching the site requirement.

Run:  python3 scripts/gen_predictions_bank.py
"""
import json
import re
from pathlib import Path

BOT_DATA = Path.home() / "ielts-predictions-bot" / "data"
OUT = Path(__file__).resolve().parent.parent / "internal" / "database" / "ielts_predictions_bot_bank.go"


def strip_header(text: str) -> str:
    """Drop the leading '🎤 Speaking Part 1 — X' / '✍️ Writing Task 2' header line."""
    return text.split("\n\n", 1)[1].strip() if "\n\n" in text else text.strip()


def header_topic(text: str) -> str:
    head = text.split("\n\n", 1)[0]
    return head.split("—", 1)[1].strip() if "—" in head else ""


def title_of(s: str, n: int = 8) -> str:
    words = re.sub(r"\s+", " ", s).strip().split(" ")
    t = " ".join(words[:n]).strip(" .,:;—-")
    return t[:70]


def go_raw(s: str) -> str:
    """Emit a Go raw-string literal; backticks can't appear inside one."""
    return "`" + s.replace("`", "'") + "`"


def load(name):
    p = BOT_DATA / name
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else []


def main():
    w2 = load("writing2.json")
    s1 = load("speaking1.json")
    s2 = load("speaking2.json")
    s3 = load("speaking3.json")

    rows = []  # each: dict of go fields

    # --- Writing Task 2 ---
    for i, item in enumerate(w2, 1):
        prompt = strip_header(item if isinstance(item, str) else item.get("text", ""))
        if not prompt:
            continue
        rows.append(dict(section="writing", qtype="task2", topic=title_of(prompt, 4),
                         title=title_of(prompt), prompt=prompt, content=None,
                         exam="predictions-2026-writing", group="predictions-2026-writing-task2",
                         band="6.5", sort=i))

    # --- Speaking Part 1 ---
    for i, item in enumerate(s1, 1):
        text = item if isinstance(item, str) else item.get("text", "")
        topic = header_topic(text) or "General"
        body = strip_header(text)
        if not body:
            continue
        rows.append(dict(section="speaking", qtype="part1", topic=topic, title=title_of(topic, 6),
                         prompt=body, content=None,
                         exam="predictions-2026-speaking", group="predictions-2026-speaking-p1",
                         band="6.0", sort=i))

    # --- Speaking Part 2 (cue card: Describe = prompt, "You should say" = content) ---
    for i, item in enumerate(s2, 1):
        text = item if isinstance(item, str) else item.get("text", "")
        body = strip_header(text)
        if not body:
            continue
        lines = [l for l in body.splitlines() if l.strip()]
        describe = lines[0].strip()
        rest = "\n".join(l.strip() for l in lines[1:]).strip()
        rest = re.sub(r"(?i)^you should say\s*:?\s*", "", rest).strip()
        rows.append(dict(section="speaking", qtype="part2", topic=title_of(describe, 6),
                         title=title_of(describe), prompt=describe, content=rest or None,
                         exam="predictions-2026-speaking", group="predictions-2026-speaking-p2",
                         band="6.5", sort=i))

    # --- Speaking Part 3 ---
    for i, item in enumerate(s3, 1):
        text = item if isinstance(item, str) else item.get("text", "")
        topic = header_topic(text) or "Discussion"
        body = strip_header(text)
        if not body:
            continue
        rows.append(dict(section="speaking", qtype="part3", topic=title_of(topic, 6), title=title_of(topic, 6),
                         prompt=body, content=None,
                         exam="predictions-2026-speaking", group="predictions-2026-speaking-p3",
                         band="6.5", sort=i))

    # --- emit Go ---
    out = []
    out.append("package database\n")
    out.append('import "github.com/midoriya/flashlearn-backend/internal/models"\n')
    out.append("// Code generated by scripts/gen_predictions_bank.py — DO NOT EDIT.")
    out.append("// Source: ~/ielts-predictions-bot/data (cleaned prediction PDFs).")
    out.append(f"// Writing Task 2 + Speaking Part 1/2/3 (text-only). {len(rows)} questions.\n")
    out.append("func buildPredictionsBotBank() []models.IELTSQuestion {")
    out.append("\treturn []models.IELTSQuestion{")
    for r in rows:
        content = f"stringPtr({go_raw(r['content'])})" if r["content"] else "nil"
        out.append("\t\t{")
        out.append(f'\t\t\tSection:       "{r["section"]}",')
        out.append(f'\t\t\tQuestionType:  "{r["qtype"]}",')
        out.append('\t\t\tDifficulty:    "medium",')
        out.append('\t\t\tMockType:      "predictions",')
        out.append(f"\t\t\tTopic:         {go_raw(r['topic'])},")
        out.append(f'\t\t\tExamSet:       "{r["exam"]}",')
        out.append(f'\t\t\tQuestionGroup: "{r["group"]}",')
        out.append(f"\t\t\tTitle:         {go_raw(r['title'])},")
        out.append(f"\t\t\tPrompt:        {go_raw(r['prompt'])},")
        out.append(f"\t\t\tContent:       {content},")
        out.append(f'\t\t\tBandTarget:    stringPtr("{r["band"]}"),')
        out.append(f"\t\t\tSortOrder:     {r['sort']},")
        out.append("\t\t},")
    out.append("\t}")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")

    from collections import Counter
    c = Counter((r["section"], r["qtype"]) for r in rows)
    print(f"wrote {OUT} with {len(rows)} questions")
    for k, v in sorted(c.items()):
        print(f"  {k[0]}/{k[1]}: {v}")


if __name__ == "__main__":
    main()
